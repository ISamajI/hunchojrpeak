const KEY = 'casa3d.lang';
let lang = 'es';
try {
  const saved = localStorage.getItem(KEY);
  if (saved === 'es' || saved === 'en') lang = saved;
} catch { /* storage blocked: stay Spanish */ }

const listeners = new Set();

export const getLang = () => lang;

export function setLang(next) {
  if (next !== 'es' && next !== 'en') return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* ignore */ }
  document.documentElement.lang = next;
  for (const fn of listeners) fn(next);
}

export const onLang = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };

export function t(key, vars) {
  const entry = D[key];
  let s = entry ? entry[lang === 'en' ? 1 : 0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

// For {es,en} objects that live in state.js (styles, palettes, items, lot presets).
export const pick = (obj) => (obj ? obj[lang] ?? obj.es : '');

// Static markup uses data-i18n / data-i18n-aria / data-i18n-title.
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.dataset.i18nTitle));
}

